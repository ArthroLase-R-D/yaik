import fk.fk_equations as fk_equations
import fk.kinematics_dh as kinematics_dh
from solver.equation_utils import find_unknown_idx
from codegen.skeleton.codegen_base import CodeGenerationBase, indent
from codegen.skeleton.skeleton_tree import SkeletonTree
from codegen.rust_codegen.scope_manager import RustScopeManager
from codegen.rust_codegen.rust_codegen_visitor import NodeIkSolutionGeneratorRust
from codegen.rust_codegen.rust_code_printer import YaikRustCodePrinter
from utility.symbolic_utils import inverse_transform
from typing import List, Optional
import sympy as sp


class CodeGenerationRust(CodeGenerationBase):
    """
    Generate a Rust module ``{robot_name}_ik_generated.rs`` from a skeleton tree.
    The module depends on yaik_rust_common.rs (the Rust counterpart of yaik_cpp_common.h), declared as a
    sibling module and imported as ``super::yaik_rust_common``. It uses nalgebra internally and accepts
    nalgebra / glam / [[f64; 4]; 4] poses through the ``Pose4`` trait.
    """

    def __init__(self, tree: SkeletonTree, use_safe_operator: bool = False):
        super().__init__(tree)
        self._code_lines: List[str] = list()
        self._scope_manager = RustScopeManager(self._code_lines)
        self._printer = YaikRustCodePrinter(use_safe_operator=use_safe_operator)
        self._generate_visitor = NodeIkSolutionGeneratorRust(tree, use_safe_operator=use_safe_operator)

    # Code line utilities
    def add_code_line(self, code_line: str):
        self._scope_manager.append_code_line(code_line)

    def add_empty_line(self):
        self.add_code_line('')

    def enter_scope(self, scope_name: str, header: Optional[str] = None):
        self._scope_manager.enter_scope(scope_name, header)

    def exit_scope(self, scope_name: Optional[str]):
        self._scope_manager.exit_scope(scope_name)

    def rust_code(self, expr: sp.Expr) -> str:
        return self._printer.doprint(expr)

    def rust_name(self, symbol: sp.Symbol) -> str:
        return self._printer.doprint(symbol)

    @staticmethod
    def float_literal(value) -> str:
        return repr(float(value))

    # Naming
    def fk_function_name(self) -> str:
        return 'compute_fk'

    def twist_jacobian_func_name(self) -> str:
        return 'compute_twist_jacobian'

    def angular_velocity_jacobian_func_name(self) -> str:
        return 'compute_angular_velocity_jacobian'

    def transform_point_jacobian_func_name(self) -> str:
        return 'compute_transform_point_jacobian'

    def ik_function_name(self, raw_ik: bool) -> str:
        return 'compute_raw_ik' if raw_ik else 'compute_ik'

    @staticmethod
    def fk_matrix_function_name() -> str:
        return 'compute_fk_matrix'

    @staticmethod
    def get_unknown_offset_name(unknown_name: str):
        return unknown_name + '_offset_original2raw'

    def has_ee_transform(self) -> bool:
        return self.robot.get_pre_transform_sp() is not None or self.robot.get_post_transform_sp() is not None

    def free_symbol_args_decl(self, include_unknown_as_parameter: bool = True) -> str:
        return ''.join(', {}: f64'.format(self.rust_name(s)) for s in self.free_symbols(include_unknown_as_parameter))

    def free_symbol_args_call(self, include_unknown_as_parameter: bool = True) -> str:
        return ''.join(', ' + self.rust_name(s) for s in self.free_symbols(include_unknown_as_parameter))

    def free_symbol_args_call_with_offset(self) -> str:
        """
        Free symbols for calling the raw ik from original values: unknowns used as parameters get their offset.
        """
        unknown_symbols = [elem.symbol for elem in self.robot.unknowns]
        has_offset = self.robot.get_unknown_offset() is not None
        args = ''
        for symbol_j in self.free_symbols():
            if symbol_j in unknown_symbols and has_offset:
                args += ', {} + {}'.format(self.rust_name(symbol_j), self.get_unknown_offset_name(symbol_j.name))
            else:
                args += ', ' + self.rust_name(symbol_j)
        return args

    # Main entry
    def generate_code(self) -> List[str]:
        self._generate_header()
        self._generate_constants()
        self._generate_ik_target_transform()
        self.add_empty_line()
        self.add_code_line('// ************* Below are the actual FK and IK implementations *******************')
        self._generate_fk_method()
        self._generate_jacobian_method()
        self._generate_raw_ik()
        self._generate_raw_ik_with_workspace()
        self._generate_unchecked_ik_method()
        self._generate_wrap_angle()
        self._generate_checked_ik_method()
        self._generate_handy_ik()
        self._generate_test_method()
        return self._code_lines

    def _generate_header(self):
        self.add_code_line('// Inverse kinematics solver for {} generated by yaik.'.format(self.robot.name))
        self.add_code_line('// Declare it next to yaik_rust_common.rs: `mod yaik_rust_common; mod {};`'.format(
            self.default_file_name() + '_generated'))
        self.add_code_line('// Requires nalgebra, rand and glam in the host crate.')
        self.add_code_line('#![allow(non_snake_case, non_upper_case_globals, unused_variables, unused_mut, '
                           'unused_parens, unused_labels, unused_imports, dead_code, clippy::all)]')
        self.add_empty_line()
        self.add_code_line('use std::f64::consts::{E, PI};')
        self.add_code_line('use nalgebra::{DMatrix, Matrix4, SMatrix, Vector3};')
        self.add_code_line('use super::yaik_rust_common::*;')

    def _generate_constants(self):
        tree = self.skeleton_tree
        robot = self.robot
        self.add_empty_line()
        self.add_code_line('// Constants for solver')
        self.add_code_line('pub const ROBOT_NQ: usize = {};'.format(len(robot.unknowns)))
        max_n_solution = 128 if tree.has_general_6dof_solution_node() else 16
        self.add_code_line('pub const MAX_N_SOLUTIONS: usize = {};'.format(max_n_solution))
        self.add_code_line('pub const N_TREE_NODES: usize = {};'.format(tree.num_nodes))
        self.add_code_line('pub const INTERMEDIATE_SOLUTION_SIZE: usize = {};'.format(len(tree.all_solved_symbol())))
        self.add_code_line('pub const POSE_TOLERANCE: f64 = 1e-6;')
        self.add_code_line('pub const POSE_TOLERANCE_DEGENERATE: f64 = 1e-4;')
        self.add_code_line('pub const {}: f64 = 1e-6;'.format(self.rust_name(fk_equations.zero_tolerance)))
        self.add_code_line('pub type IkWorkspace = RawIkWorkspace<INTERMEDIATE_SOLUTION_SIZE, MAX_N_SOLUTIONS, ROBOT_NQ>;')

        self.add_empty_line()
        self.add_code_line('// Robot parameters')
        parameter_values = tree.solved_equation_record.parameter_value_dict
        for parameter in parameter_values:
            self.add_code_line('pub const {name}: f64 = {value};'.format(
                name=self.rust_name(parameter), value=self.float_literal(parameter_values[parameter])))

        self.add_empty_line()
        self.add_code_line('// Unknown offsets from original unknown value to raw value')
        self.add_code_line('// Original value are the ones corresponded to robot (usually urdf/sdf)')
        self.add_code_line('// Raw value are the ones used in the solver')
        self.add_code_line('// unknown_i_raw = unknown_i_original + unknown_i_offset_original2raw')
        unknown_offset = robot.get_unknown_offset()
        if unknown_offset is not None:
            assert len(unknown_offset) == len(robot.unknowns)
            for unknown_i, offset_i in zip(robot.unknowns, unknown_offset):
                self.add_code_line('pub const {name}: f64 = {value};'.format(
                    name=self.get_unknown_offset_name(unknown_i.symbol.name), value=self.float_literal(offset_i)))

    # End-effector transforms
    def _generate_direct_forward_ee_transform(self, func_name: str):
        assert self._scope_manager.indent_level == 0
        self.enter_scope(func_name, 'pub fn {}(T_ee: &Matrix4<f64>) -> Matrix4<f64>'.format(func_name))
        self.add_code_line('*T_ee')
        self.exit_scope(func_name)

    def _generate_ee_transform_sp(self, func_name: str,
                                  left_4x4_multiply: Optional[sp.Matrix],
                                  right_4x4_multiply: Optional[sp.Matrix]):
        left_4x4 = sp.Matrix(sp.eye(4) if left_4x4_multiply is None else left_4x4_multiply)
        right_4x4 = sp.Matrix(sp.eye(4) if right_4x4_multiply is None else right_4x4_multiply)
        ik_target_4x4 = fk_equations.ik_target_4x4()
        transformed_4x4 = left_4x4 * (ik_target_4x4 * right_4x4)

        assert self._scope_manager.indent_level == 0
        self.enter_scope(func_name, 'pub fn {}(T_ee: &Matrix4<f64>) -> Matrix4<f64>'.format(func_name))
        for r in range(3):
            for c in range(4):
                self.add_code_line('let {name}: f64 = T_ee[({r}, {c})];'.format(
                    name=self.rust_name(ik_target_4x4[r, c]), r=r, c=c))
        self.add_code_line('let mut ee_transformed = Matrix4::<f64>::identity();')
        for r in range(3):
            for c in range(4):
                expr_code = self.rust_code(sp.simplify(transformed_4x4[r, c]))
                self.add_code_line('ee_transformed[({r}, {c})] = {code};'.format(r=r, c=c, code=expr_code))
        self.add_code_line('ee_transformed')
        self.exit_scope(func_name)

    def _generate_ik_target_transform(self):
        self.add_empty_line()
        self.add_code_line('// The transformation between raw and original ee target')
        self.add_code_line('// Original value are the ones corresponded to robot (usually urdf/sdf)')
        self.add_code_line('// Raw value are the ones used in the solver')
        self.add_code_line('// ee_original = pre_transform * ee_raw * post_transform')
        self.add_code_line('// ee_raw = dh_forward_transform(theta_raw)')
        if not self.has_ee_transform():
            self._generate_direct_forward_ee_transform('end_effector_target_original_to_raw')
            self.add_empty_line()
            self._generate_direct_forward_ee_transform('end_effector_target_raw_to_original')
            return

        pre_transform = self.robot.get_pre_transform_sp()
        post_transform = self.robot.get_post_transform_sp()
        pre_transform_inv = None if pre_transform is None else inverse_transform(pre_transform)
        post_transform_inv = None if post_transform is None else inverse_transform(post_transform)
        self._generate_ee_transform_sp('end_effector_target_original_to_raw', pre_transform_inv, post_transform_inv)
        self.add_empty_line()
        self._generate_ee_transform_sp('end_effector_target_raw_to_original', pre_transform, post_transform)

    # FK and jacobian
    def _add_unknown_extraction_lines(self):
        self.add_code_line('// Extract the variables')
        unknown_offset = self.robot.get_unknown_offset()
        for i, unknown_i in enumerate(self.robot.unknowns):
            symbol_i = unknown_i.symbol
            if unknown_offset is None:
                self.add_code_line('let {var}: f64 = theta_input_original[{idx}];'.format(
                    var=self.rust_name(symbol_i), idx=i))
            else:
                self.add_code_line('let {var}: f64 = theta_input_original[{idx}] + {offset};'.format(
                    var=self.rust_name(symbol_i), idx=i, offset=self.get_unknown_offset_name(symbol_i.name)))

    def _add_cse_temp_lines(self, replacements):
        self.add_empty_line()
        self.add_code_line('// Temp variable for efficiency')
        for symbol_i, expr_i in replacements:
            self.add_code_line('let {var}: f64 = {code};'.format(var=self.rust_name(symbol_i), code=self.rust_code(expr_i)))
        self.add_code_line('// End of temp variables')

    def _generate_fk_method(self):
        robot = self.robot
        fk_name = self.fk_matrix_function_name()
        args = self.free_symbol_args_decl(include_unknown_as_parameter=False)
        self.add_empty_line()
        self.add_code_line('/// Forward kinematics of the original (urdf/sdf) joint values')
        self.enter_scope(fk_name, 'pub fn {name}(theta_input_original: &[f64; ROBOT_NQ]{args}) -> Matrix4<f64>'.
                         format(name=fk_name, args=args))
        unknown_symbols = [elem.symbol for elem in robot.unknowns]
        ee_pose = kinematics_dh.forward_kinematics_dh(robot.dh_params, unknown_symbols).T_ee()
        self._add_unknown_extraction_lines()

        fk_expressions: List[sp.Expr] = [ee_pose[i, j] for i in range(3) for j in range(4)]
        replacements, reduced_expressions = sp.cse(fk_expressions)
        self._add_cse_temp_lines(replacements)

        self.add_code_line('let mut ee_pose_raw = Matrix4::<f64>::identity();')
        for i in range(3):
            for j in range(4):
                self.add_code_line('ee_pose_raw[({i}, {j})] = {code};'.format(
                    i=i, j=j, code=self.rust_code(reduced_expressions[j + i * 4])))
        self.add_code_line('end_effector_target_raw_to_original(&ee_pose_raw)')
        self.exit_scope(fk_name)

        # Generic wrapper
        self.add_empty_line()
        self.add_code_line('/// Forward kinematics returning any Pose4 type, e.g. nalgebra::Matrix4<f64> or glam::DMat4')
        self.enter_scope('fk', 'pub fn {name}<P: Pose4>(theta_input_original: &[f64; ROBOT_NQ]{args}) -> P'.format(
            name=self.fk_function_name(), args=args))
        self.add_code_line('P::from_matrix4(&{fk}(theta_input_original{call}))'.format(
            fk=fk_name, call=self.free_symbol_args_call(include_unknown_as_parameter=False)))
        self.exit_scope('fk')

    def _generate_twist_or_angular_or_point_jacobian_impl(self, jacobian_matrix: sp.Matrix, jacobian_func_name: str,
                                                          point_jacobian_point_on_ee: Optional[List[sp.Symbol]] = None):
        n_rows = jacobian_matrix.shape[0]
        args = self.free_symbol_args_decl(include_unknown_as_parameter=False)
        if point_jacobian_point_on_ee is not None:
            assert len(point_jacobian_point_on_ee) == 3
            args += ', point_on_ee: &Vector3<f64>'
        args += ', jacobian: &mut SMatrix<f64, {}, ROBOT_NQ>'.format(n_rows)

        self.add_empty_line()
        self.enter_scope(jacobian_func_name, 'pub fn {name}(theta_input_original: &[f64; ROBOT_NQ]{args})'.format(
            name=jacobian_func_name, args=args))
        self._add_unknown_extraction_lines()
        if point_jacobian_point_on_ee is not None:
            for i in range(3):
                self.add_code_line('let {var}: f64 = point_on_ee[{idx}];'.format(
                    var=self.rust_name(point_jacobian_point_on_ee[i]), idx=i))

        jacobian_expressions: List[sp.Expr] = [jacobian_matrix[i, j] for i in range(n_rows)
                                               for j in range(jacobian_matrix.shape[1])]
        replacements, reduced_expressions = sp.cse(jacobian_expressions)
        self._add_cse_temp_lines(replacements)

        self.add_empty_line()
        self.add_code_line('jacobian.fill(0.0);')
        counter = 0
        for i in range(n_rows):
            for j in range(jacobian_matrix.shape[1]):
                out_ij_expr: sp.Expr = reduced_expressions[counter]
                counter += 1
                if out_ij_expr != sp.S.Zero:
                    self.add_code_line('jacobian[({i}, {j})] = {code};'.format(i=i, j=j, code=self.rust_code(out_ij_expr)))
        self.exit_scope(jacobian_func_name)

    def _generate_jacobian_method(self):
        robot = self.robot
        unknown_symbols = [elem.symbol for elem in robot.unknowns]
        jacobian_twist = kinematics_dh.twist_jacobian_dh(robot.dh_params, unknown_symbols, robot.get_pre_transform_sp())
        self._generate_twist_or_angular_or_point_jacobian_impl(jacobian_twist, self.twist_jacobian_func_name())
        self._generate_twist_or_angular_or_point_jacobian_impl(jacobian_twist[0:3, :],
                                                               self.angular_velocity_jacobian_func_name())
        p_on_ee = sp.zeros(3, 1)
        p_on_ee[0] = sp.Symbol('p_on_ee_x')
        p_on_ee[1] = sp.Symbol('p_on_ee_y')
        p_on_ee[2] = sp.Symbol('p_on_ee_z')
        point_jacobian: sp.Matrix = sp.zeros(3, jacobian_twist.shape[1])
        for c in range(jacobian_twist.shape[1]):
            point_jacobian[:, c] = jacobian_twist[0:3, c].cross(p_on_ee) + jacobian_twist[3:6, c]
        self._generate_twist_or_angular_or_point_jacobian_impl(
            point_jacobian, self.transform_point_jacobian_func_name(), [p_on_ee[0], p_on_ee[1], p_on_ee[2]])

    # Raw IK
    def _generate_raw_ik(self):
        self.add_empty_line()
        self.add_code_line('/// Raw ik on the raw end-effector target, appends the raw joint values to ik_output')
        self.enter_scope('raw_ik', 'pub fn compute_raw_ik_with_queues(T_ee: &Matrix4<f64>{args}, '
                                   'solution_queue: &mut SolutionQueue<INTERMEDIATE_SOLUTION_SIZE, MAX_N_SOLUTIONS>, '
                                   'node_index_workspace: &mut NodeIndexWorkspace<MAX_N_SOLUTIONS>, '
                                   'ik_output: &mut Vec<[f64; ROBOT_NQ]>)'.format(args=self.free_symbol_args_decl()))

        self.add_code_line('// Extracting the ik target symbols')
        ik_4x4 = fk_equations.ik_target_4x4()
        for r in range(3):
            for c in range(4):
                self.add_code_line('let {name}: f64 = T_ee[({r}, {c})];'.format(
                    name=self.rust_name(ik_4x4[r, c]), r=r, c=c))
        self.add_code_line('let inv_ee_translation = -(T_ee.fixed_view::<3, 3>(0, 0).transpose() '
                           '* T_ee.fixed_view::<3, 1>(0, 3));')
        inv_ik_4x4 = fk_equations.ik_target_inv_4x4()
        for i in range(3):
            self.add_code_line('let {name}: f64 = inv_ee_translation[{idx}];'.format(
                name=self.rust_name(inv_ik_4x4[i, 3]), idx=i))

        visitor = self._generate_visitor
        assert len(visitor.generated_code_lines) == 0
        visitor.append_init_lines()
        self.skeleton_tree.preorder_visit(visitor)
        visitor.append_finalize_lines()
        for this_line in visitor.generated_code_lines:
            self._code_lines.append(indent() + this_line if len(this_line) > 0 else '')
        self.exit_scope('raw_ik')

    def _generate_raw_ik_with_workspace(self):
        self.add_empty_line()
        self.add_code_line('/// Raw ik on the raw end-effector target, the result is in workspace.raw_ik_out')
        self.enter_scope('workspace_raw_ik', 'pub fn {name}(T_ee_raw: &Matrix4<f64>{args}, workspace: &mut IkWorkspace)'.
                         format(name=self.ik_function_name(True), args=self.free_symbol_args_decl()))
        self.add_code_line('workspace.raw_ik_out.clear();')
        # The parameter input is already raw value, no offset here
        self.add_code_line('compute_raw_ik_with_queues(T_ee_raw{call}, &mut workspace.solution_queue, '
                           '&mut workspace.node_index_workspace, &mut workspace.raw_ik_out);'.
                           format(call=self.free_symbol_args_call()))
        self.exit_scope('workspace_raw_ik')

    def _add_to_raw_target_line(self):
        self.add_code_line('let T_ee = T_ee.to_matrix4();')
        if self.has_ee_transform():
            self.add_code_line('let T_ee_raw = end_effector_target_original_to_raw(&T_ee);')
        else:
            self.add_code_line('let T_ee_raw = T_ee;')

    def _add_offset_lines(self, var_name: str = 'ik_out_i'):
        unknown_offset = self.robot.get_unknown_offset()
        if unknown_offset is None:
            return
        for j, unknown_j in enumerate(self.robot.unknowns):
            self.add_code_line('{var}[{j}] -= {offset};'.format(
                var=var_name, j=j, offset=self.get_unknown_offset_name(unknown_j.symbol.name)))

    def _generate_unchecked_ik_method(self):
        self.add_empty_line()
        self.add_code_line('/// IK without the fk check, joint values are original (urdf/sdf) values')
        self.enter_scope('un_checked_ik', 'pub fn compute_ik_unchecked<P: Pose4>(T_ee: &P{args}, '
                                          'workspace: &mut IkWorkspace, ik_output: &mut Vec<[f64; ROBOT_NQ]>)'.
                         format(args=self.free_symbol_args_decl()))
        self._add_to_raw_target_line()
        self.add_code_line('{raw}(&T_ee_raw{call}, workspace);'.format(
            raw=self.ik_function_name(True), call=self.free_symbol_args_call_with_offset()))
        self.add_code_line('ik_output.clear();')
        self.enter_scope('for', 'for raw_ik_out_i in workspace.raw_ik_out.iter()')
        self.add_code_line('let mut ik_out_i = *raw_ik_out_i;')
        self._add_offset_lines()
        self.add_code_line('ik_output.push(ik_out_i);')
        self.exit_scope('for')
        self.exit_scope('un_checked_ik')

    def _generate_wrap_angle(self):
        self.add_empty_line()
        self.add_code_line('/// Wrap the revolute joint values to [-pi, pi]')
        self.enter_scope('wrap_angle', 'pub fn wrap_angle_to_pi(ik_output: &mut [[f64; ROBOT_NQ]])')
        self.enter_scope('for_each_solution', 'for solution_i in ik_output.iter_mut()')
        for j, unknown_j in enumerate(self.robot.unknowns):
            if not unknown_j.is_revolute:
                continue
            self.add_code_line('// Revolute unknown {}'.format(unknown_j.symbol.name))
            self.add_code_line('solution_i[{j}] = wrap_angle_value_to_pi(solution_i[{j}]);'.format(j=j))
        self.exit_scope('for_each_solution')
        self.exit_scope('wrap_angle')

    def _generate_checked_ik_method(self):
        self.add_empty_line()
        fk_call_args = self.free_symbol_args_call(include_unknown_as_parameter=False)
        fk_name = self.fk_matrix_function_name()
        self.add_code_line('/// IK with fk check and degenerate handling, joint values are original (urdf/sdf) values')
        self.enter_scope('checked_ik', 'pub fn compute_ik_with_workspace<P: Pose4>(T_ee: &P{args}, '
                                       'workspace: &mut IkWorkspace, ik_output: &mut Vec<[f64; ROBOT_NQ]>)'.
                         format(args=self.free_symbol_args_decl()))
        self._add_to_raw_target_line()
        raw_call = '{raw}(&{{target}}{call}, workspace);'.format(
            raw=self.ik_function_name(True), call=self.free_symbol_args_call_with_offset())
        self.add_code_line(raw_call.format(target='T_ee_raw'))

        self.add_code_line('ik_output.clear();')
        self.enter_scope('for', 'for raw_ik_out_i in workspace.raw_ik_out.iter()')
        self.add_code_line('let mut ik_out_i = *raw_ik_out_i;')
        self._add_offset_lines()
        self.add_code_line('let ee_pose_i = {fk}(&ik_out_i{args});'.format(fk=fk_name, args=fk_call_args))
        self.add_code_line('let ee_pose_diff = (ee_pose_i - T_ee).norm_squared();')
        self.enter_scope('if', 'if ee_pose_diff < POSE_TOLERANCE')
        self.add_code_line('ik_output.push(ik_out_i);')
        self.exit_scope('if')
        self.exit_scope('for')

        self.add_empty_line()
        self.enter_scope('if_valid_solution', 'if !ik_output.is_empty()')
        self.add_code_line('wrap_angle_to_pi(ik_output);')
        self.add_code_line('remove_duplicate(ik_output, zero_tolerance);')
        self.add_code_line('return;')
        self.exit_scope('if_valid_solution')

        self.add_empty_line()
        self.add_code_line('// Disturbing method for degenerate handling')
        self.add_code_line('let T_ee_raw_disturbed = disturb_transform(&T_ee_raw);')
        self.add_code_line('let T_ee_disturbed = end_effector_target_raw_to_original(&T_ee_raw_disturbed);')
        self.add_code_line(raw_call.format(target='T_ee_raw_disturbed'))
        self.enter_scope('for', 'for raw_ik_out_i in workspace.raw_ik_out.iter()')
        self.add_code_line('let mut ik_out_i = *raw_ik_out_i;')
        self._add_offset_lines()
        self.add_code_line('let ee_pose_i = {fk}(&ik_out_i{args});'.format(fk=fk_name, args=fk_call_args))
        self.add_code_line('if (ee_pose_i - T_ee_disturbed).norm_squared() > POSE_TOLERANCE_DEGENERATE {')
        self.add_code_line('    continue;')
        self.add_code_line('}')
        self.add_empty_line()
        self.add_code_line('// Try numerical refinement')
        self.add_code_line('numerical_refinement(')
        self.add_code_line('    |q: &[f64; ROBOT_NQ]| {fk}(q{args}),'.format(fk=fk_name, args=fk_call_args))
        self.add_code_line('    |q: &[f64; ROBOT_NQ], jacobian: &mut SMatrix<f64, 6, ROBOT_NQ>| '
                           '{jac}(q{args}, jacobian),'.format(jac=self.twist_jacobian_func_name(), args=fk_call_args))
        self.add_code_line('    &T_ee,')
        self.add_code_line('    &mut ik_out_i,')
        self.add_code_line(');')
        self.add_code_line('let ee_pose_i = {fk}(&ik_out_i{args});'.format(fk=fk_name, args=fk_call_args))
        self.enter_scope('if', 'if (ee_pose_i - T_ee).norm_squared() < POSE_TOLERANCE_DEGENERATE')
        self.add_code_line('ik_output.push(ik_out_i);')
        self.exit_scope('if')
        self.exit_scope('for')

        self.add_empty_line()
        self.add_code_line('wrap_angle_to_pi(ik_output);')
        self.add_code_line('remove_duplicate(ik_output, zero_tolerance);')
        self.exit_scope('checked_ik')

    def _generate_handy_ik(self):
        self.add_empty_line()
        self.add_code_line('/// IK with fk check, joint values are original (urdf/sdf) values')
